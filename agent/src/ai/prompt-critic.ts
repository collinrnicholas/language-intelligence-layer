import { callLLM } from '../llm/index.js';

export interface PromptCriticScores {
  productUnderstanding: number;
  uxReasoning: number;
  missingContext: number;
  ambiguity: number;
  specificity: number;
  confidence: number;
}

export interface PromptCriticResult {
  applied: boolean;
  overallScore: number;
  scores: PromptCriticScores;
  rationale: string;
  changesMade: string[];
  reviewedBriefMarkdown: string;
  raw: string;
}

/** A surgical rewrite of a single prose section, keyed by its `## ` heading. */
export interface SectionRewrite {
  heading: string;
  newBody: string;
}

interface PromptCriticJson {
  overallScore?: unknown;
  scores?: Partial<Record<keyof PromptCriticScores, unknown>>;
  rationale?: unknown;
  issues?: unknown;
  sectionRewrites?: unknown;
}

const SCORE_KEYS: Array<keyof PromptCriticScores> = [
  'productUnderstanding',
  'uxReasoning',
  'missingContext',
  'ambiguity',
  'specificity',
  'confidence',
];

const PASS_THRESHOLD = 9;

// ─── Section model ──────────────────────────────────────────────
//
// The brief is a sequence of `## ` sections after a preamble (title + goal
// blockquote). The critic may only rewrite PROSE sections — those with no
// `### B<n>.` BUILD findings. Finding sections carry the reviewer's exact quotes,
// measured CSS state, and acceptance criteria; the critic never rewrites them, so
// that evidence is protected by construction rather than by a post-hoc guard.

interface BriefSection {
  heading: string;
  hasFindings: boolean;
}

const FINDING_RE = /^### B\d+\./m;

// Deterministic, template-generated prose sections the critic may SCORE (they
// count toward the quality gate) but must never REWRITE — a model rewrite would
// desync them from the copied artifact / measured evidence they mirror.
const PROTECTED_PROSE_HEADINGS = new Set(['Target Design']);

/** A section is off-limits to rewrites if it carries findings OR is a protected prose section. */
function isRewriteProtected(s: BriefSection): boolean {
  return s.hasFindings || PROTECTED_PROSE_HEADINGS.has(s.heading);
}

function briefSections(brief: string): BriefSection[] {
  const out: BriefSection[] = [];
  const re = /^## (.+?)[ \t]*$/gm;
  const heads: { heading: string; index: number }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(brief)) !== null) heads.push({ heading: m[1].trim(), index: m.index });
  for (let i = 0; i < heads.length; i++) {
    const body = brief.slice(heads[i].index, i + 1 < heads.length ? heads[i + 1].index : brief.length);
    out.push({ heading: heads[i].heading, hasFindings: FINDING_RE.test(body) });
  }
  return out;
}

/** Replace the body of one `## <heading>` section, leaving every other byte of
 *  the brief untouched. Returns null if the heading isn't found. */
function applySectionRewrite(brief: string, heading: string, newBody: string): string | null {
  const esc = heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  // No `m` flag: `$` must mean end-of-string, so the lazy body spans to the next
  // `## ` heading or the document end — not to the first blank line.
  const re = new RegExp(`((?:^|\\n)## ${esc}[ \\t]*\\n)([\\s\\S]*?)(?=\\n## |$)`);
  if (!re.test(brief)) return null;
  return brief.replace(re, (_full, head: string) => `${head}\n${newBody.trim()}\n`);
}

/**
 * Review the final implementation prompt as if it is about to be handed to an
 * autonomous coding agent. If it scores below the quality bar, apply the model's
 * targeted section rewrites; the brief's structure and per-finding evidence are
 * preserved by construction.
 */
export async function critiqueImplementationBrief(
  briefMarkdown: string,
  meta: {
    project?: string;
    flow?: string;
    target?: string;
    goal?: string;
  } = {},
  opts: { model?: string } = {},
): Promise<PromptCriticResult | null> {
  const sections = briefSections(briefMarkdown);
  const prose = sections.filter(s => !isRewriteProtected(s)).map(s => s.heading);
  const protectedSecs = sections.filter(isRewriteProtected).map(s => s.heading);

  // The footer's generation timestamp is noise to the critic, and — because it
  // changes every run — it was the one byte-level difference defeating response
  // caching for otherwise identical briefs. Neutralize it in the PROMPT only;
  // section rewrites are applied to the untouched original below.
  const briefForReview = briefMarkdown.replace(
    /^\*Generated by Loupe — [^*\n]+\*$/m,
    '*Generated by Loupe*',
  );

  const prompt = [
    'You are Loupe\'s final implementation-brief critic.',
    '',
    'The brief below will be handed directly to an AI coding agent such as Claude Code or Codex.',
    'Your job is practical: decide whether the agent will know exactly what to build, why it matters,',
    'what evidence supports it, and how to verify the result.',
    '',
    'Score the brief from 1 to 10 on these dimensions:',
    '- productUnderstanding: Does it explain what product/screen/workflow this is?',
    '- uxReasoning: Does it explain the UX/product reason behind the requested changes?',
    '- missingContext: 10 means no important context is missing; 1 means major context is missing.',
    '- ambiguity: 10 means unambiguous; 1 means vague or contradictory.',
    '- specificity: Does it name concrete targets, constraints, evidence, and acceptance criteria?',
    '- confidence: How confident are you that a coding agent could execute this without asking follow-up questions?',
    '',
    `If overallScore is ${PASS_THRESHOLD} or higher, return an empty sectionRewrites array — the brief ships as-is.`,
    `If overallScore is below ${PASS_THRESHOLD}, propose targeted rewrites for the weak PROSE sections only.`,
    '',
    '━━━ How to return edits — surgical, not wholesale ━━━',
    '',
    'You do NOT return the whole brief. You return a list of section rewrites. Each entry names an',
    'existing section heading verbatim and gives ONLY the new body text for that one section.',
    '',
    `PROSE sections you MAY rewrite (these carry no BUILD findings): ${prose.map(h => `"${h}"`).join(', ') || '(none)'}.`,
    `PROTECTED sections you must NEVER include: ${protectedSecs.map(h => `"${h}"`).join(', ') || '(none)'}.`,
    'The protected sections contain the reviewer\'s exact quotes, measured CSS state, and acceptance',
    'criteria. They are off-limits — any rewrite targeting them is discarded.',
    '',
    'Rules for each rewrite body:',
    '  - Do NOT invent selectors, CSS values, file paths, finding titles, or acceptance criteria.',
    '  - Do NOT add or remove sections; only the named prose sections change.',
    '  - Keep it as markdown that drops straight into that section (no `## ` heading line — body only).',
    '',
    '━━━ What good rewrites do ━━━',
    '',
    '- Sharpen Goal & Context, UX/Product synthesis, and How-to-Work prose.',
    '- Remove hedging phrases and generic UX filler.',
    '- Make the product goal and build order clearer and more concrete.',
    '',
    'Return ONLY valid JSON with this exact shape:',
    '{',
    '  "overallScore": 8,',
    '  "scores": {',
    '    "productUnderstanding": 8,',
    '    "uxReasoning": 8,',
    '    "missingContext": 9,',
    '    "ambiguity": 8,',
    '    "specificity": 8,',
    '    "confidence": 8',
    '  },',
    '  "rationale": "One short paragraph.",',
    '  "issues": ["Specific weakness you found"],',
    '  "sectionRewrites": [',
    '    { "heading": "Goal & Context", "newBody": "The improved prose for this section." }',
    '  ]',
    '}',
    '',
    `PROJECT: ${meta.project || '(unknown)'}`,
    `FLOW: ${meta.flow || '(unknown)'}`,
    `GOAL: ${meta.goal || '(unknown)'}`,
    `TARGET AGENT: ${meta.target || '(unknown)'}`,
    '',
    'IMPLEMENTATION BRIEF TO REVIEW:',
    briefForReview,
  ].join('\n');

  let raw: string;
  try {
    raw = await callLLM('build', prompt, {
      severity: 'High',
      contextSize: 'large',
      maxTokens: 4000,
      promptVersion: 'prompt-critic-v2',
      stage: 'prompt-critic',
      ...(opts.model ? { model: opts.model } : {}),
      meta: { project: meta.project, flow: meta.flow },
    });
  } catch {
    return null;
  }

  const parsed = parsePromptCriticResponse(raw, briefMarkdown);
  if (!parsed) return null;

  return { ...parsed, raw };
}

export function parsePromptCriticResponse(raw: string, originalBrief: string): Omit<PromptCriticResult, 'raw'> | null {
  const data = extractJson(raw);
  if (!data) return null;

  const overallScore = score(data.overallScore);
  if (overallScore === null) return null;

  const scores = parseScores(data.scores);
  if (!scores) return null;

  const rationale = typeof data.rationale === 'string' ? data.rationale.trim() : '';
  const issues = Array.isArray(data.issues)
    ? data.issues.filter((i): i is string => typeof i === 'string' && i.trim().length > 0)
    : [];

  const rewrites = parseSectionRewrites(data.sectionRewrites);
  const sections = briefSections(originalBrief);
  const protectedSet = new Set(sections.filter(isRewriteProtected).map(s => s.heading));
  const known = new Set(sections.map(s => s.heading));

  // Below-threshold briefs get their weak prose sections rewritten in place;
  // at/above threshold, no rewrite is applied regardless of what the model returned.
  const shouldRewrite = overallScore < PASS_THRESHOLD;

  let markdown = originalBrief;
  const changesMade: string[] = [];
  if (shouldRewrite) {
    for (const rw of rewrites) {
      if (!known.has(rw.heading)) {
        changesMade.push(`[critic-guard] Ignored rewrite for unknown section "${rw.heading}".`);
        continue;
      }
      if (protectedSet.has(rw.heading)) {
        changesMade.push(`[critic-guard] Refused rewrite of protected section "${rw.heading}".`);
        continue;
      }
      const next = applySectionRewrite(markdown, rw.heading, rw.newBody);
      if (next && next !== markdown) {
        markdown = next;
        changesMade.push(`Rewrote "${rw.heading}".`);
      }
    }
  }

  const applied = markdown.trim() !== originalBrief.trim();
  // Surface the model's own issue list too, so debug artifact 09 explains the score.
  for (const issue of issues) changesMade.push(issue);

  return {
    applied,
    overallScore,
    scores,
    rationale,
    changesMade,
    reviewedBriefMarkdown: markdown,
  };
}

function parseSectionRewrites(data: unknown): SectionRewrite[] {
  if (!Array.isArray(data)) return [];
  const out: SectionRewrite[] = [];
  for (const item of data) {
    if (!item || typeof item !== 'object') continue;
    const heading = (item as Record<string, unknown>).heading;
    const newBody = (item as Record<string, unknown>).newBody;
    if (typeof heading === 'string' && heading.trim() && typeof newBody === 'string' && newBody.trim()) {
      out.push({ heading: heading.trim(), newBody });
    }
  }
  return out;
}

function parseScores(data: PromptCriticJson['scores']): PromptCriticScores | null {
  if (!data || typeof data !== 'object') return null;
  const out: Partial<PromptCriticScores> = {};
  for (const key of SCORE_KEYS) {
    const value = score(data[key]);
    if (value === null) return null;
    out[key] = value;
  }
  return out as PromptCriticScores;
}

function score(value: unknown): number | null {
  const n = typeof value === 'number' ? value : typeof value === 'string' ? Number(value) : NaN;
  if (!Number.isFinite(n)) return null;
  return Math.max(1, Math.min(10, n));
}

function extractJson(raw: string): PromptCriticJson | null {
  const cleaned = raw.replace(/```json\s*/gi, '').replace(/```/g, '').trim();
  const candidates = [
    cleaned,
    cleaned.slice(cleaned.indexOf('{'), cleaned.lastIndexOf('}') + 1),
  ].filter(s => s.startsWith('{') && s.endsWith('}'));

  for (const candidate of candidates) {
    try {
      return JSON.parse(candidate) as PromptCriticJson;
    } catch {
      // Try the next candidate.
    }
  }
  return null;
}
