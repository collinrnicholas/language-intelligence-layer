import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import type { LoupeSession, Opportunity } from '../cli.js';
import { generateImplementationBrief, renderBriefToMarkdown, GOALS } from './implementation-brief.js';
import type { GoalName, TargetName } from './implementation-brief.js';
import { designSystemPaths } from '../paths.js';
import { extractScreenshots, extractedCount } from '../screenshots.js';

export interface PackageOptions {
  findings: Opportunity[];
  session: LoupeSession;
  goal: GoalName;
  target: TargetName;
  outputDir?: string;
}

/**
 * Generate a full implementation package.
 *
 * Creates:
 *   implementation/
 *     summary.md
 *     build-prompt.md       (the Implementation Brief)
 *     acceptance-criteria.md
 *     screenshots/          (extracted JPEGs)
 *     findings.json
 *     design-system.json    (if available)
 *     context.json
 */
export function generateImplementationPackage(opts: PackageOptions): string {
  const { findings, session, goal, target } = opts;
  const goalDef = GOALS[goal];

  // Determine output directory. Each run gets a unique child folder so stale
  // screenshots or old prompt files cannot leak into a new package.
  const baseOutputDir = opts.outputDir || join(dirname(process.cwd()), 'implementation-packages');
  mkdirSync(baseOutputDir, { recursive: true });
  const outputDir = uniquePackageDir(baseOutputDir, session.project, session.flow);
  mkdirSync(outputDir, { recursive: true });

  console.log(`Generating implementation package in ${outputDir}...`);

  // ─── 1. summary.md ────────────────────────────────────────────
  const severityCounts = {
    Critical: findings.filter(f => f.severity === 'Critical').length,
    High: findings.filter(f => f.severity === 'High').length,
    Medium: findings.filter(f => f.severity === 'Medium').length,
    Low: findings.filter(f => f.severity === 'Low').length,
    Info: findings.filter(f => f.severity === 'Info').length,
  };

  const summary = [
    `# Implementation Summary — ${session.project}`,
    '',
    `**Flow:** ${session.flow}`,
    `**Goal:** ${goal} — ${goalDef.description}`,
    `**Target:** ${target}`,
    `**Generated:** ${new Date().toISOString()}`,
    '',
    '## Findings to fix',
    `| Severity | Count |`,
    `|----------|-------|`,
    ...Object.entries(severityCounts)
      .filter(([, count]) => count > 0)
      .map(([sev, count]) => `| ${sev} | ${count} |`),
    `| **Total** | **${findings.length}** |`,
    '',
    '## Files in this package',
    '| File | Description |',
    '|------|-------------|',
    '| `build-prompt.md` | Full implementation brief for AI coding agents |',
    '| `acceptance-criteria.md` | Checklist for verification |',
    '| `findings.json` | Raw findings data (machine-readable) |',
    '| `context.json` | Session context (URLs, events, notes) |',
    '| `screenshots/` | Extracted screenshot images |',
    '| `design-system.json` | Project design tokens (if available) |',
    '',
    '## Quick start',
    '',
    `cat build-prompt.md | ${targetToCommand(target)}`,
    '',
    `*Generated by Loupe*`,
  ].join('\n');

  writeFileSync(join(outputDir, 'summary.md'), summary);
  console.log('  ✓ summary.md');

  // ─── 2. build-prompt.md (Implementation Brief) ────────────────
  const brief = generateImplementationBrief(findings, session, goal, target);
  const markdown = renderBriefToMarkdown(brief);
  writeFileSync(join(outputDir, 'build-prompt.md'), markdown);
  console.log('  ✓ build-prompt.md');

  // ─── 3. acceptance-criteria.md ────────────────────────────────
  // Source from the brief's consolidated acceptance (same items shown per-finding);
  // f.acceptanceCriteria is never populated by analyze, so it would be blank.
  const criteria = brief.acceptanceCriteria;
  if (criteria.length === 0) {
    console.warn(`  ⚠ acceptance-criteria.md has no finding-level criteria — ${brief.findings.length} narrated finding(s). Expected only when BUILD is empty.`);
  }
  const criteriaMd = [
    '# Acceptance Criteria',
    '',
    `**Goal:** ${goal}`,
    `**Findings to verify:** ${brief.findings.length}`,
    '',
    ...(criteria.length > 0
      ? criteria.map((c, i) => `- [ ] ${i + 1}. ${c}`)
      : ['- [ ] _No narrated findings to build — nothing to verify._']
    ),
    '',
    '## Post-implementation checks',
    '- [ ] All findings resolved',
    '- [ ] No new console errors',
    '- [ ] Design tokens used (no hardcoded values)',
    '- [ ] Visual comparison: before/after screenshots match expectations',
    '- [ ] Loupe re-review score improved',
  ].join('\n');

  writeFileSync(join(outputDir, 'acceptance-criteria.md'), criteriaMd);
  console.log('  ✓ acceptance-criteria.md');

  // ─── 4. findings.json ────────────────────────────────────────
  writeFileSync(join(outputDir, 'findings.json'), JSON.stringify(findings, null, 2));
  console.log('  ✓ findings.json');

  // ─── 5. context.json ─────────────────────────────────────────
  const context = {
    project: session.project,
    flow: session.flow,
    startedAt: session.startedAt,
    endedAt: session.endedAt,
    urlTimeline: session.urlTimeline,
    eventCount: session.events.length,
    screenshotCount: session.screenshots.length,
    noteCount: session.notes.length,
    notes: session.notes.filter(n => n.type === 'transcript').map(n => ({
      timestamp: n.timestamp,
      text: n.text,
    })),
  };
  writeFileSync(join(outputDir, 'context.json'), JSON.stringify(context, null, 2));
  console.log('  ✓ context.json');

  // ─── 6. screenshots/ ─────────────────────────────────────────
  const rels = extractScreenshots(session, join(outputDir, 'screenshots'));
  console.log(`  ✓ screenshots/ (${extractedCount(rels)} extracted)`);

  // ─── 7. design-system.json ───────────────────────────────────
  let dsCopied = false;
  for (const p of designSystemPaths(session.project)) {
    if (existsSync(p)) {
      writeFileSync(join(outputDir, 'design-system.json'), readFileSync(p));
      console.log('  ✓ design-system.json');
      dsCopied = true;
      break;
    }
  }
  if (!dsCopied) {
    console.log('  - design-system.json (not available)');
  }

  console.log(`\n✓ Package ready: ${outputDir}`);
  console.log(`  Feed to ${target}: cat ${outputDir}/build-prompt.md | ${targetToCommand(target)}`);

  return outputDir;
}

function targetToCommand(target: string): string {
  switch (target) {
    case 'Claude Code': return 'claude';
    case 'Cursor': return '# Open in Cursor and use as context';
    case 'Codex': return 'codex';
    case 'Gemini CLI': return 'gemini';
    default: return '# Pipe to your AI coding agent';
  }
}

function uniquePackageDir(baseDir: string, project: string, flow: string): string {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const slug = `${slugify(project)}-${slugify(flow)}`.replace(/^-|-$/g, '') || 'session';
  let candidate = join(baseDir, `${stamp}-${slug}`);
  let suffix = 1;
  while (existsSync(candidate)) {
    candidate = join(baseDir, `${stamp}-${slug}-${suffix++}`);
  }
  return candidate;
}

function slugify(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}
