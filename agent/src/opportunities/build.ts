import type { LoupeSession, Opportunity } from '../cli.js';
import { generateImplementationBrief, renderBriefToMarkdown, GOALS } from '../ai/implementation-brief.js';
import type { GoalName, TargetName } from '../ai/implementation-brief.js';
import type { ReasoningContext } from './context.js';
import { renderEvidenceBlock } from './context.js';

export interface BuildOutput {
  /** The full markdown brief */
  markdown: string;
  /** Metadata */
  goal: string;
  target: string;
  opportunityCount: number;
}

/**
 * Generate a Build This implementation brief from shared context.
 * For a single opportunity, generates a focused brief.
 * For multiple, merges into a coherent plan.
 */
export function buildThis(
  contexts: ReasoningContext[],
  session: LoupeSession,
  goal: GoalName,
  target: TargetName
): BuildOutput {
  const opportunities = contexts.map(c => c.opportunity);

  if (opportunities.length === 1) {
    // Single opportunity — use the full brief generator
    const brief = generateImplementationBrief(opportunities, session, goal, target);
    const markdown = renderBriefToMarkdown(brief);
    return { markdown, goal, target, opportunityCount: 1 };
  }

  // Multiple opportunities — merge into a coherent plan
  return buildMergedBrief(contexts, session, goal, target);
}

/**
 * Merge multiple opportunities into one coherent implementation brief.
 */
function buildMergedBrief(
  contexts: ReasoningContext[],
  session: LoupeSession,
  goal: GoalName,
  target: TargetName
): BuildOutput {
  const opportunities = contexts.map(c => c.opportunity);
  const goalDef = GOALS[goal];
  const sessionUrl = session.urlTimeline[0]?.url || '';

  const lines: string[] = [];

  lines.push(`# Implementation Brief — ${session.project} / ${session.flow}`);
  lines.push('');
  lines.push(`> **Goal:** ${goal} — ${goalDef.description}`);
  lines.push(`> **Target:** ${target}`);
  lines.push(`> **Opportunities addressed:** ${opportunities.length}`);
  lines.push('');
  lines.push('---');

  // Executive Summary
  lines.push('');
  lines.push('## Executive Summary');
  lines.push(`This brief addresses ${opportunities.length} opportunities identified by Loupe's AI review.`);
  lines.push('Each fix is prioritized and can be implemented independently.');
  lines.push('');

  // Priority order
  const sorted = [...opportunities].sort((a, b) => {
    const rank: Record<string, number> = { Critical: 0, High: 1, Medium: 2, Low: 3, Info: 4 };
    return (rank[a.severity] || 5) - (rank[b.severity] || 5);
  });

  lines.push('## Implementation Order');
  sorted.forEach((o, i) => {
    lines.push(`**${i + 1}.** [${o.severity}] ${o.title}${o.selector ? ` → \`${o.selector}\`` : ''}`);
  });
  lines.push('');

  // Individual opportunity briefs
  for (let i = 0; i < contexts.length; i++) {
    const ctx = contexts[i];
    const o = ctx.opportunity;

    lines.push('---');
    lines.push('');
    lines.push(`## ${i + 1}. ${o.title}`);
    lines.push(`**Severity:** ${o.severity} | **Category:** ${o.category} | **Confidence:** ${Math.round(o.confidence * 100)}%`);
    lines.push('');

    lines.push('### Current State');
    lines.push(o.description);
    lines.push('');

    if (o.suggestedFix) {
      lines.push('### Recommended Fix');
      lines.push(o.suggestedFix);
      lines.push('');
    }

    lines.push('### Evidence');
    lines.push(renderEvidenceBlock(ctx.evidence));
    lines.push('');

    if (o.acceptanceCriteria?.length) {
      lines.push('### Acceptance Criteria');
      o.acceptanceCriteria.forEach(c => lines.push(`- [ ] ${c}`));
      lines.push('');
    }
  }

  // Shared constraints
  lines.push('---');
  lines.push('');
  lines.push('## Constraints');
  lines.push('- Each phase can be implemented independently.');
  lines.push('- Preserve existing functionality outside the scope of these changes.');
  if (goal === 'Minimal changes') lines.push('- Minimum diff — fix only what is broken.');
  if (goal === 'Accessibility-first') lines.push('- All changes must meet WCAG 2.1 AA.');
  lines.push('');

  // Success metrics
  lines.push('## Success Metrics');
  lines.push(`- [ ] All ${opportunities.length} opportunities resolved`);
  lines.push('- [ ] No new console errors');
  lines.push('- [ ] Design tokens used (no hardcoded values)');
  lines.push('- [ ] Loupe re-review score improved');
  lines.push('');

  lines.push('---');
  lines.push(`*Generated by Loupe — ${new Date().toISOString()}*`);

  return {
    markdown: lines.join('\n'),
    goal,
    target,
    opportunityCount: opportunities.length,
  };
}
